<?php
namespace XcVm\Domain\Assistant;

use XcVm\Core\Auth\Authorization;
use XcVm\Domain\Line\LineService;
use XcVm\Domain\User\ResellerAPI;
use XcVm\Domain\User\UserCredits;
use XcVm\Domain\User\UserService;

/** Creation is a reviewed purchase, never an instruction to execute arbitrary code. */
final class CreationTools {
    public function __construct(private string $scope) {}

    private function allowed(string $kind): bool {
        return $this->scope === 'admin'
            ? Authorization::check('adv', $kind === 'line' ? 'add_user' : 'add_reguser')
            : ($this->scope === 'reseller' && Authorization::hasResellerPermissions($kind === 'line' ? 'create_line' : 'create_sub_resellers'));
    }

    public function definitions(): array {
        $result = [];
        $id = ['type'=>'integer','minimum'=>1];
        $username = ['type'=>'string','maxLength'=>80,'description'=>'Requested username, or empty string for automatic generation. Never send passwords.'];
        $catalog = [
            'creation_options'=>[$this->allowed('line') || $this->allowed('reseller'), 'Read available official subscription packages and reseller groups, prices, naming policy and your balance before proposing creation.', []],
            'create_subscription'=>[$this->allowed('line'), 'PROPOSE creating ONE normal subscription owned by you using the selected official package. Resellers pay their effective package price; admins use administrative creation without a credit charge. Ask the user to select a package; never guess. Password is generated by the server after confirmation.', ['package_id'=>$id,'username'=>$username]],
            'create_subscriptions_bulk'=>[$this->allowed('line'), 'PROPOSE one atomic batch of 2 to 50 normal subscriptions with server-generated usernames/passwords. The user must specify count and official package. Show total price and remaining balance for confirmation. Resellers pay effective unit price times count; admin creation has no debit.', ['package_id'=>$id,'count'=>['type'=>'integer','minimum'=>2,'maximum'=>50]]],
            'create_reseller'=>[$this->allowed('reseller'), 'PROPOSE creating ONE non-admin reseller owned by you in the selected allowed group. Specify initial_credits explicitly (ask if missing). Resellers pay creation fee AND transfer initial credits from their own balance. Admins issue initial credits without a debit. Password is generated by the server after confirmation.', ['group_id'=>$id,'username'=>$username,'initial_credits'=>['type'=>'number','minimum'=>0,'maximum'=>100000]]],
        ];
        foreach ($catalog as $name=>[$allowed,$description,$properties]) {
            if ($allowed) { $result[]=['type'=>'function','function'=>['name'=>$name,'description'=>$description,'parameters'=>['type'=>'object','properties'=>$properties ?: new \stdClass(),'required'=>array_keys($properties),'additionalProperties'=>false]]]; }
        }
        return $result;
    }

    private function rows(string $sql, mixed ...$args): array {
        global $db;
        if (!$db->query($sql,...$args)) { throw new \RuntimeException('DATABASE_ERROR'); }
        return $db->get_raw_rows();
    }

    private function write(string $sql, mixed ...$args): void {
        global $db;
        if (!$db->query($sql,...$args)) { throw new \RuntimeException('DATABASE_ERROR'); }
    }

    private function revision(array $row): string { return hash('sha256',json_encode($row,JSON_THROW_ON_ERROR)); }

    private function context(bool $lock=false): array {
        global $rUserInfo;
        $actor=$this->rows('SELECT * FROM `users` WHERE `id`=?'.($lock?' FOR UPDATE':''),(int)$rUserInfo['id'])[0]??[];
        if (!$actor || (int)$actor['status']!==1) { throw new \RuntimeException('FORBIDDEN'); }
        $group=$this->rows('SELECT * FROM `users_groups` WHERE `group_id`=?'.($lock?' FOR UPDATE':''),(int)$actor['member_group_id'])[0]??[];
        if (!$group || empty($group[$this->scope==='admin'?'is_admin':'is_reseller'])) { throw new \RuntimeException('FORBIDDEN'); }
        return [$actor,$group];
    }

    private function amount(mixed $value): float {
        if (!is_numeric($value) || !is_finite((float)$value) || (float)$value<0 || abs(round((float)$value,4)-(float)$value)>0.0000001) { throw new \RuntimeException('INVALID_ARGUMENTS'); }
        return round((float)$value,4);
    }

    private function packageAllowed(array $package,array $actor): bool {
        return !empty($package['is_line']) && !empty($package['is_official']) && ($this->scope==='admin' || in_array((int)$actor['member_group_id'],array_map('intval',json_decode($package['groups']??'[]',true)?:[]),true));
    }

    private function groupAllowed(array $group,array $policy): bool {
        return !empty($group['is_reseller']) && empty($group['is_admin']) && ($this->scope==='admin' || in_array((int)$group['group_id'],array_map('intval',json_decode($policy['subresellers']??'[]',true)?:[]),true));
    }

    private function price(array $package,array $actor): float {
        if ($this->scope==='admin') { return 0.0; }
        $overrides=json_decode($actor['override_packages']??'{}',true)?:[];
        $override=$overrides[$package['id']]['official_credits']??null;
        return $this->amount($override!==null && (string)$override!=='' ? $override : $package['official_credits']);
    }

    public function call(string $name,array $args): array {
        if ($name==='creation_options') {
            if ($args) { throw new \RuntimeException('INVALID_ARGUMENTS'); }
            if (!$this->allowed('line') && !$this->allowed('reseller')) { throw new \RuntimeException('FORBIDDEN'); }
            [$actor,$policy]=$this->context();$packages=[];$groups=[];
            if ($this->allowed('line')) {
                foreach ($this->rows('SELECT * FROM `users_packages` WHERE `is_line`=1 AND `is_official`=1 ORDER BY `id`') as $p) {
                    if ($this->packageAllowed($p,$actor)) { $packages[]=['id'=>(int)$p['id'],'name'=>$p['package_name'],'credits'=>$this->price($p,$actor),'duration'=>$p['official_duration'],'unit'=>$p['official_duration_in'],'connections'=>$p['max_connections']]; }
                    if (count($packages)>=30) { break; }
                }
            }
            if ($this->allowed('reseller')) {
                foreach ($this->rows('SELECT * FROM `users_groups` WHERE `is_reseller`=1 AND `is_admin`=0 ORDER BY `group_id`') as $g) {
                    if ($this->groupAllowed($g,$policy)) { $groups[]=['id'=>(int)$g['group_id'],'name'=>$g['group_name']]; }
                    if (count($groups)>=30) { break; }
                }
            }
            return ['packages'=>$packages,'reseller_groups'=>$groups,'your_credits'=>$this->amount($actor['credits']),
                'reseller_creation_fee'=>$this->scope==='admin'?0:$this->amount($policy['create_sub_resellers_price']??0),
                'initial_credits_policy'=>$this->scope==='admin'?'Issued administratively, no debit':'Transferred from your balance in addition to creation fee',
                'custom_username_allowed'=>$this->scope==='admin'||!empty($policy['allow_change_username']),
                'minimum_username_length'=>$this->scope==='admin'?1:(int)$policy['minimum_username_length'],
                'password'=>'Generated on server and shown only after confirmation','owner_id'=>(int)$actor['id'],'limit'=>30];
        }
        return ['proposal'=>$name==='create_subscriptions_bulk'?$this->proposeBulk($args):$this->propose($name,$args)];
    }

    private function propose(string $name,array $args,bool $lock=false): array {
        $line=$name==='create_subscription';
        if (!$line && $name!=='create_reseller') { throw new \RuntimeException('FORBIDDEN'); }
        if (!$this->allowed($line?'line':'reseller')) { throw new \RuntimeException('FORBIDDEN'); }
        $keys=$line?['package_id','username']:['group_id','username','initial_credits'];$idKey=$line?'package_id':'group_id';
        if (count($args)!==count($keys) || array_diff(array_keys($args),$keys) || !is_int($args[$idKey]??null) || $args[$idKey]<1 || !is_string($args['username']??null)
            || !preg_match('/^[A-Za-z0-9_.-]{0,80}$/D',$args['username'])) { throw new \RuntimeException('INVALID_ARGUMENTS'); }
        [$actor,$policy]=$this->context($lock);
        $username=$args['username'];
        if ($username!=='' && $this->scope==='reseller' && (empty($policy['allow_change_username']) || strlen($username)<(int)$policy['minimum_username_length'])) { throw new \RuntimeException('INVALID_ARGUMENTS'); }
        if ($username!=='' && $this->rows('SELECT `id` FROM `'.($line?'lines':'users').'` WHERE `username`=?',$username)) { throw new \RuntimeException('USERNAME_EXISTS'); }
        $selected=$this->rows('SELECT * FROM `'.($line?'users_packages':'users_groups').'` WHERE `'.($line?'id':'group_id').'`=?'.($lock?' FOR UPDATE':''),$args[$idKey])[0]??[];
        if (!$selected || !($line?$this->packageAllowed($selected,$actor):$this->groupAllowed($selected,$policy))) { throw new \RuntimeException('FORBIDDEN'); }
        $initial=0.0;
        if (!$line) {
            if (!is_int($args['initial_credits']) && !is_float($args['initial_credits'])) { throw new \RuntimeException('INVALID_ARGUMENTS'); }
            $initial=$this->amount($args['initial_credits']);
            if ($initial>100000 || ($this->scope==='reseller' && floor($initial)!=$initial)) { throw new \RuntimeException('INVALID_ARGUMENTS'); }
        }
        $fee=$line?$this->price($selected,$actor):($this->scope==='admin'?0.0:$this->amount($policy['create_sub_resellers_price']??0));
        $debit=$this->scope==='admin'?0.0:round($fee+$initial,4);
        if ($this->amount($actor['credits'])<$debit) { throw new \RuntimeException('INSUFFICIENT_CREDITS'); }
        $details=['Owner / المالك: '.$actor['username'].' (#'.$actor['id'].')',
            ($line?'Package / الباقة: ':'Group / المجموعة: ').($selected[$line?'package_name':'group_name']).' (#'.$args[$idKey].')',
            'Creation cost / تكلفة الإنشاء: '.number_format($fee,4,'.',''),
            'Total debit / إجمالي الخصم: '.number_format($debit,4,'.',''),
            'Your balance / رصيدك: '.$actor['credits'].' → '.number_format((float)$actor['credits']-$debit,4,'.','')];
        if ($line) {
            if ((int)$selected['official_duration']<1 || !in_array($selected['official_duration_in'],['hours','days','months','years','hour','day','month','year'],true)) { throw new \RuntimeException('INVALID_ARGUMENTS'); }
            $details[]='Term from creation / المدة من الإنشاء: '.$selected['official_duration'].' '.$selected['official_duration_in'];
            $details[]='Connections / الاتصالات: '.$selected['max_connections'];
            $details[]='Package bouquets, subject to owner limits / باقات المحتوى حسب حدود المالك: '.$selected['bouquets'];
        } else { $details[]='Initial reseller balance / رصيد الريسيلر الجديد: '.number_format($initial,4,'.',''); }
        if ($this->scope==='admin') { $details[]='Administrative creation; no debit / إنشاء إداري بدون خصم من رصيدك'; }
        $details[]='Password generated after confirmation / كلمة المرور تتولد بعد التأكيد';
        return ['kind'=>'creation','tool'=>$name,'arguments'=>$args,'revision'=>$this->revision([$actor,$policy,$selected]),'fee'=>$fee,'debit'=>$debit,
            'public'=>['title'=>$name,'target'=>$username!==''?$username:'Automatic username / اسم مستخدم تلقائي','details'=>$details]];
    }

    private function proposeBulk(array $args,bool $lock=false): array {
        if (count($args)!==2 || array_diff(array_keys($args),['package_id','count']) || !is_int($args['count']??null) || $args['count']<2 || $args['count']>50) { throw new \RuntimeException('INVALID_ARGUMENTS'); }
        $single=$this->propose('create_subscription',['package_id'=>$args['package_id']??null,'username'=>''],$lock);
        [$actor]=$this->context();
        $total=round($single['debit']*$args['count'],4);
        if ($this->amount($actor['credits'])<$total) { throw new \RuntimeException('INSUFFICIENT_CREDITS'); }
        $details=$single['public']['details'];
        $details[2]='Unit price / سعر الاشتراك الواحد: '.number_format($single['fee'],4,'.','');
        $details[3]='Total debit / إجمالي الخصم: '.number_format($total,4,'.','');
        $details[4]='Your balance / رصيدك: '.$actor['credits'].' → '.number_format((float)$actor['credits']-$total,4,'.','');
        array_unshift($details,'Count / العدد: '.$args['count']);
        $details[]='All subscriptions and charges commit together / إنشاء وخصم الدفعة بالكامل أو إلغاء الكل';
        return ['kind'=>'creation','tool'=>'create_subscriptions_bulk','arguments'=>$args,'revision'=>$single['revision'],'unit_price'=>$single['fee'],'debit'=>$total,
            'public'=>['title'=>'create_subscriptions_bulk','target'=>$args['count'].' subscriptions / اشتراك — automatic usernames / أسماء تلقائية','details'=>$details]];
    }

    public function execute(array $proposal): array {
        if (($proposal['tool']??'')!=='create_subscriptions_bulk') { return $this->executeOne($proposal); }
        global $db;
        if (!$db->beginTransaction()) { throw new \RuntimeException('DATABASE_ERROR'); }
        $created=[];
        try {
            $fresh=$this->proposeBulk($proposal['arguments'],true);
            if (!hash_equals($proposal['revision'],$fresh['revision'])) { throw new \RuntimeException('STALE_PROPOSAL'); }
            [$actor]=$this->context();
            for ($i=0;$i<$fresh['arguments']['count'];$i++) {
                // Native sale reads the current locked balance for every member of the batch.
                $single=$this->propose('create_subscription',['package_id'=>$fresh['arguments']['package_id'],'username'=>''],true);
                $result=$this->executeOne($single,false);
                $created[]=$result['created'];
            }
            $balance=UserCredits::balance((int)$actor['id']);
            if (abs($balance-((float)$actor['credits']-$fresh['debit']))>0.00001) { throw new \RuntimeException('CREATION_REFUSED'); }
            $this->write("INSERT INTO `users_logs` (`owner`,`type`,`action`,`log_id`,`package_id`,`cost`,`credits_after`,`date`,`deleted_info`) VALUES (?, 'assistant', 'create_subscriptions_bulk', NULL, ?, ?, ?, ?, ?)",
                (int)$actor['id'],$fresh['arguments']['package_id'],0,$balance,time(),json_encode(['source'=>'ai_assistant','count'=>count($created),'total_debit'=>$fresh['debit'],'line_ids'=>array_column($created,'id')]));
            if (!$db->commit()) { throw new \RuntimeException('DATABASE_ERROR'); }
        } catch (\Throwable $error) { $db->rollback();throw $error; }
        $signal=false;
        foreach ($created as $item) { try { LineService::updateLineSignal($item['id']); } catch (\Throwable $error) { $signal=true; } }
        return ['saved'=>true,'signal_pending'=>$signal,'created_batch'=>$created,'credits_after'=>$balance,'total_debit'=>$fresh['debit']];
    }

    private function executeOne(array $proposal,bool $transaction=true): array {
        global $db,$rUserInfo;
        if ($transaction && !$db->beginTransaction()) { throw new \RuntimeException('DATABASE_ERROR'); }
        try {
            $fresh=$this->propose($proposal['tool'],$proposal['arguments'],true);
            if (!hash_equals($proposal['revision'],$fresh['revision'])) { throw new \RuntimeException('STALE_PROPOSAL'); }
            $args=$proposal['arguments'];$line=$proposal['tool']==='create_subscription';
            [$actor,$policy]=$this->context();
            $length=max(24,(int)($policy['minimum_password_length']??8));
            if ($length>128) { throw new \RuntimeException('INVALID_ARGUMENTS'); }
            $password=substr(bin2hex(random_bytes($length)),0,$length);
            $username=$args['username'];
            if ($username==='') { $username=substr(bin2hex(random_bytes(64)),0,max(12,min(80,(int)($policy['minimum_username_length']??8)))); }
            $form=['username'=>$username,'password'=>$password];
            if ($line) {
                $p=$this->rows('SELECT * FROM `users_packages` WHERE `id`=?',$args['package_id'])[0];
                $form+=['member_id'=>(int)$actor['id'],'package'=>$args['package_id'],'contact'=>'','reseller_notes'=>'','isp_clear'=>'keep'];
                if ($this->scope==='reseller') { ResellerAPI::init((int)$actor['id']);$result=ResellerAPI::processLine($form); }
                else {
                    $form+=['package_id'=>$p['id'],'exp_date'=>date('Y-m-d H:i:s',strtotime('+'.(int)$p['official_duration'].' '.$p['official_duration_in'])),
                        'max_connections'=>(int)$p['max_connections'],'bouquets_selected'=>$p['bouquets'],'access_output'=>json_decode($p['output_formats']??'[]',true)?:[],
                        'force_server_id'=>$p['force_server_id']??0,'forced_country'=>$p['forced_country']??''];
                    foreach (['is_restreamer','is_isplock'] as $flag) { if (!empty($p[$flag])) { $form[$flag]=1; } }
                    $result=LineService::process($form);
                }
            } else {
                $form+=['member_group_id'=>$args['group_id'],'owner_id'=>(int)$actor['id'],'email'=>'','reseller_dns'=>'','notes'=>'','credits'=>0];
                if ($this->scope==='reseller') { ResellerAPI::init((int)$actor['id']);$result=ResellerAPI::processUser($form,true); }
                else { $result=UserService::process($form); }
            }
            if (!is_array($result) || ($result['status']??null)!==STATUS_SUCCESS || empty($result['data']['insert_id'])) { throw new \RuntimeException('CREATION_REFUSED'); }
            $id=(int)$result['data']['insert_id'];
            if (!$line && $args['initial_credits']>0) {
                $ok=$this->scope==='reseller'?UserCredits::transfer((int)$actor['id'],$id,(float)$args['initial_credits']):UserCredits::credit($id,(float)$args['initial_credits']);
                if (!$ok) { throw new \RuntimeException('INSUFFICIENT_CREDITS'); }
                $this->write('INSERT INTO `users_credits_logs` (`target_id`,`admin_id`,`amount`,`date`,`reason`) VALUES (?,?,?,?,?)',$id,(int)$actor['id'],$args['initial_credits'],time(),'[AI] Initial reseller credits');
            }
            $stored=$this->rows('SELECT `id`,`username`,'.($line?'`password`,`member_id`':'`owner_id`,`member_group_id`').' FROM `'.($line?'lines':'users').'` WHERE `id`=?',$id)[0]??[];
            if (!$stored || (int)$stored[$line?'member_id':'owner_id']!==(int)$actor['id'] || (!$line && (int)$stored['member_group_id']!==$args['group_id'])) { throw new \RuntimeException('CREATION_REFUSED'); }
            if ($args['username']!=='' && $stored['username']!==$args['username']) { throw new \RuntimeException('CREATION_REFUSED'); }
            $credentials=$line?['username'=>$stored['username'],'password'=>$stored['password']]:($this->scope==='reseller'?($result['created_credentials']??null):['username'=>$stored['username'],'password'=>$password]);
            if (!is_array($credentials) || empty($credentials['password'])) { throw new \RuntimeException('CREATION_REFUSED'); }
            $balance=UserCredits::balance((int)$actor['id']);
            if (abs($balance-((float)$actor['credits']-$fresh['debit']))>0.00001) { throw new \RuntimeException('CREATION_REFUSED'); }
            $this->write("INSERT INTO `users_logs` (`owner`,`type`,`action`,`log_id`,`package_id`,`cost`,`credits_after`,`date`,`deleted_info`) VALUES (?, 'assistant', ?, ?, ?, ?, ?, ?, ?)",
                (int)$actor['id'],$proposal['tool'],$id,$line?$args['package_id']:null,$fresh['fee'],$balance,time(),json_encode(['source'=>'ai_assistant','initial_credits'=>$args['initial_credits']??0,'debit'=>$fresh['debit']]));
            if ($transaction && !$db->commit()) { throw new \RuntimeException('DATABASE_ERROR'); }
        } catch (\Throwable $error) { if ($transaction) { $db->rollback(); } throw $error; }
        $signal=false;
        if ($line && $transaction) { try { LineService::updateLineSignal($id); } catch (\Throwable $error) { $signal=true; } }
        // Returned directly to the authenticated browser; never appended to model history.
        return ['saved'=>true,'signal_pending'=>$signal,'created'=>['kind'=>$line?'subscription':'reseller','id'=>$id,'credentials'=>$credentials],'credits_after'=>$balance];
    }
}
