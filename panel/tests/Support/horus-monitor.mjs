import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context = {window:{}, document:{addEventListener(){}}};
vm.runInNewContext(fs.readFileSync(new URL('../../src/Public/assets/admin/xcvm/horus-monitor.js', import.meta.url),'utf8'), context);
const tasks = new Map(); let id=0, calls=0, allowed=true, release;
const clock = {setTimeout(fn){tasks.set(++id,fn);return id;},clearTimeout(key){tasks.delete(key);}};
const fire = async () => {const [key,fn]=tasks.entries().next().value;tasks.delete(key);await fn();};
const runner = context.window.HorusMonitor.scheduler(async()=>{calls++;},()=>allowed,clock);
assert.equal(tasks.size,1);
allowed=false;await fire();assert.equal(calls,0);assert.equal(tasks.size,1);
allowed=true;runner.pause(true);await fire();assert.equal(calls,0);
runner.pause(false);await fire();assert.equal(calls,1);runner.stop();assert.equal(tasks.size,0);
const slow = context.window.HorusMonitor.scheduler(()=>{calls++;return new Promise(resolve=>release=resolve);},()=>true,clock);
const pending=fire();assert.equal(tasks.size,0);assert.equal(calls,2);
slow.stop();release();await pending;assert.equal(tasks.size,0);
const retry = context.window.HorusMonitor.scheduler(()=>Promise.reject(new Error('offline')),()=>true,clock);
await fire();assert.equal(tasks.size,1);retry.stop();
console.log('PASS: hidden/ineligible pages, pause/resume, no overlapping refresh, cleanup during a request and network recovery');
